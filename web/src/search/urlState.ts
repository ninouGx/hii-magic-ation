export const DEFAULT_SORT: SortKey[] = [{ field: 'edhrec_rank', direction: 'asc' }]

/** `card` is the oracle_id open in the detail window, `selection` the id of the selection that receives cards. */
export type SearchState = { filter: RuleGroupType; sort: SortKey[]; card?: string | null; selection?: string | null }

/** Ids are regenerated by the query builder, so the URL leaves them out. */
export function encodeSearch(state: SearchState): string {
  const params = new URLSearchParams()
  params.set('filter', JSON.stringify(state.filter, (key, value) => (key === 'id' || key === 'path' ? undefined : value)))
  params.set('sort', JSON.stringify(state.sort))
  if (state.card) params.set('card', state.card)
  if (state.selection) params.set('selection', state.selection)
  return `?${params}`
}

/** A missing or broken parameter falls back to its default. */
export function decodeSearch(search: string): SearchState {
  const params = new URLSearchParams(search)
  return {
    filter: parse(params.get('filter'), isGroup) ?? DEFAULT_FILTER,
    sort: parse(params.get('sort'), isSort) ?? DEFAULT_SORT,
    card: params.get('card'),
    selection: params.get('selection'),
  }
}

function parse<T>(raw: string | null, guard: (value: unknown) => value is T): T | null {
  if (raw === null) return null
  try {
    const value: unknown = JSON.parse(raw)
    return guard(value) ? value : null
  } catch {
    return null
  }
}

function isGroup(value: unknown): value is RuleGroupType {
  return typeof value === 'object' && value !== null && 'combinator' in value && Array.isArray((value as RuleGroupType).rules)
}

function isSort(value: unknown): value is SortKey[] {
  return (
    Array.isArray(value) &&
    value.every(
      (key) =>
        typeof key === 'object' &&
        key !== null &&
        typeof key.field === 'string' &&
        (key.direction === 'asc' || key.direction === 'desc'),
    )
  )
}
